function unwrap(response) {
  var data = response;

  if (
    data &&
    typeof data === "object" &&
    data.data !== undefined
  ) {
    data = data.data;
  }

  if (typeof data === "string") {
    data = JSON.parse(data);
  }

  return data;
}

function positiveId(value) {
  var n = Number(value);

  return Number.isSafeInteger(n) && n > 0
    ? n
    : null;
}

function tmdbPath(value) {
  return (
    typeof value === "string" &&
    /^\/[^/]/.test(value)
  ) ? value : "";
}

function tmdbUrl(path) {
  return path
    ? "https://image.tmdb.org/t/p/original" + path
    : "";
}

function errString(error) {
  return error && error.message
    ? error.message
    : String(error);
}

/*
 * EXISTING TRAKT LISTS
 *
 * Preserve the order generated by your
 * four-hour GitHub Actions workflow.
 */

async function fetchTraktList(
  slug,
  mediaType,
  clientId
) {
  var key = String(clientId || "").trim();

  if (!key) {
    throw new Error(
      "Missing Trakt Client ID. Enter it in Rex."
    );
  }

  var url =
    "https://api.trakt.tv/users/" +
    encodeURIComponent(TRAKT_USER) +
    "/lists/" +
    encodeURIComponent(slug) +
    "/items";

  var response = await Widget.http.get(url, {
    headers: {
      Accept: "application/json",
      "trakt-api-version": "2",
      "trakt-api-key": key
    },
    params: {
      page: 1,
      limit: 100
    }
  });

  var data = unwrap(response);

  if (
    data &&
    !Array.isArray(data) &&
    Array.isArray(data.items)
  ) {
    data = data.items;
  }

  if (!Array.isArray(data)) {
    throw new Error(
      "Invalid Trakt list response: " + slug
    );
  }

  var keyName =
    mediaType === "movie" ? "movie" : "show";

  var ranked = data
    .filter(function(row) {
      return row && (
        row[keyName] ||
        row.type === keyName
      );
    })
    .map(function(row, index) {
      var rank = Number(row.rank);

      return {
        row: row,
        rank:
          Number.isInteger(rank) && rank > 0
            ? rank
            : index + 1,
        index: index
      };
    });

  ranked.sort(function(a, b) {
    return a.rank - b.rank || a.index - b.index;
  });

  if (ranked.length < MAX_ITEMS) {
    console.warn(
      "Trakt returned",
      ranked.length,
      "titles for",
      slug
    );
  }

  ranked = ranked.slice(0, MAX_ITEMS);

  if (!ranked.length) {
    throw new Error(
      "No titles returned: " + slug
    );
  }

  return ranked;
}

/*
 * TEXTLESS POSTER SELECTION
 *
 * Prioritize high-resolution, language-neutral
 * TMDB posters.
 *
 * If no suitable image exists, use the
 * regular official poster instead.
 */

function chooseCleanPoster(posters) {
  if (!Array.isArray(posters)) {
    return "";
  }

  var suitable = posters.filter(function(p) {
    var w = Number(p && p.width) || 0;
    var h = Number(p && p.height) || 0;
    var ratio = h ? w / h : 0;

    return (
      p &&
      p.iso_639_1 == null &&
      tmdbPath(p.file_path) &&
      w >= 600 &&
      h >= 900 &&
      ratio >= 0.60 &&
      ratio <= 0.75
    );
  });

  suitable.sort(function(a, b) {
    var voteA = Number(a.vote_average) || 0;
    var voteB = Number(b.vote_average) || 0;

    var sizeA =
      (Number(a.width) || 0) *
      (Number(a.height) || 0);

    var sizeB =
      (Number(b.width) || 0) *
      (Number(b.height) || 0);

    return (
      (voteB - voteA) * 1000000 +
      (sizeB - sizeA)
    );
  });

  return suitable.length
    ? suitable[0].file_path
    : "";
}

/*
 * TITLE LOGOS
 *
 * Prefer English-language image logos.
 * Fall back to language-neutral images.
 */

function chooseLogo(logos) {
  if (!Array.isArray(logos)) {
    return "";
  }

  var suitable = logos.filter(function(p) {
    return (
      p &&
      tmdbPath(p.file_path) &&
      /\.(png|webp)$/i.test(p.file_path) &&
      (
        p.iso_639_1 === "en" ||
        p.iso_639_1 == null
      )
    );
  });

  suitable.sort(function(a, b) {
    var enA = a.iso_639_1 === "en" ? 1 : 0;
    var enB = b.iso_639_1 === "en" ? 1 : 0;

    if (enB !== enA) {
      return enB - enA;
    }

    return (
      (Number(b.width) || 0) *
      (Number(b.height) || 0)
    ) - (
      (Number(a.width) || 0) *
      (Number(a.height) || 0)
    );
  });

  return suitable.length
    ? suitable[0].file_path
    : "";
}

function chooseStandardPoster(posters) {
  if (!Array.isArray(posters)) {
    return "";
  }

  var suitable = posters.filter(function(p) {
    return p && tmdbPath(p.file_path);
  });

  suitable.sort(function(a, b) {
    var aEn = a.iso_639_1 === "en" ? 1 : 0;
    var bEn = b.iso_639_1 === "en" ? 1 : 0;

    if (aEn !== bEn) {
      return bEn - aEn;
    }

    return (
      (Number(b.width) || 0) *
      (Number(b.height) || 0)
    ) - (
      (Number(a.width) || 0) *
      (Number(a.height) || 0)
    );
  });

  return suitable.length
    ? suitable[0].file_path
    : "";
}

/*
 * TMDB ARTWORK AND METADATA
 *
 * Request artwork together with the details.
 * Use a separate gallery request only when
 * the combined response lacks image data.
 */

async function getArtwork(
  mediaType,
  tmdbId,
  title
) {
  var info = {
    standardPoster: "",
    cleanPoster: "",
    logo: "",
    backdrop: "",
    genres: [],
    network: "",
    networkLogo: ""
  };

  var details = null;
  var images = null;

  try {
    var response = await Widget.tmdb.get(
      mediaType + "/" + tmdbId,
      {
        params: {
          language: "en-US",
          append_to_response: "images",
          include_image_language: "en,null"
        }
      }
    );

    details = unwrap(response);

    if (details) {
      info.standardPoster = tmdbPath(
        details.poster_path ||
        details.posterPath
      );

      info.backdrop = tmdbPath(
        details.backdrop_path ||
        details.backdropPath
      );

      if (Array.isArray(details.genres)) {
        info.genres = details.genres
          .map(function(g) {
            return g && g.name
              ? String(g.name)
              : "";
          })
          .filter(Boolean);
      }

      if (
        mediaType === "tv" &&
        Array.isArray(details.networks) &&
        details.networks.length
      ) {
        var network = details.networks[0];

        info.network = String(
          network.name || ""
        );

        info.networkLogo = tmdbPath(
          network.logo_path
        );
      }

      images = details.images || null;
    }
  } catch (error) {
    console.warn(
      "TMDB details failed:",
      title,
      errString(error)
    );
  }

  if (
    !images ||
    !Array.isArray(images.posters) ||
    !Array.isArray(images.logos)
  ) {
    try {
      var galleryResponse =
        await Widget.tmdb.get(
          mediaType + "/" + tmdbId + "/images",
          {
            params: {
              include_image_language: "en,null"
            }
          }
        );

      images = unwrap(galleryResponse);
    } catch (error) {
      console.warn(
        "TMDB image gallery failed:",
        title,
        errString(error)
      );
    }
  }

  if (images) {
    info.cleanPoster = chooseCleanPoster(
      images.posters
    );

    info.logo = chooseLogo(
      images.logos
    );

    if (!info.standardPoster) {
      info.standardPoster =
        chooseStandardPoster(
          images.posters
        );
    }
  }

  return info;
}

/*
 * IMDb -> TMDB ID FALLBACK
 */

async function resolveTmdbId(
  mediaType,
  imdbId
) {
  if (!/^tt\d+$/.test(imdbId || "")) {
    return null;
  }

  try {
    var response = await Widget.tmdb.get(
      "find/" + imdbId,
      {
        params: {
          external_source: "imdb_id"
        }
      }
    );

    var data = unwrap(response) || {};

    var found =
      mediaType === "movie"
        ? data.movie_results
        : data.tv_results;

    return (
      Array.isArray(found) &&
      found.length
    ) ? positiveId(found[0].id) : null;
  } catch (error) {
    console.warn(
      "IMDb/TMDB lookup failed:",
      imdbId,
      errString(error)
    );

    return null;
  }
}

/*
 * PRESERVE THE 90S CLUB POSTER FIX
 */

function isNinetiesClub(
  title,
  tmdbId,
  imdbId,
  mediaType
) {
  return (
    mediaType === "movie" &&
    (
      tmdbId === 950237 ||
      imdbId === "tt18225078" ||
      String(title || "")
        .trim()
        .toLowerCase() === "the 90s club"
    )
  );
}

/*
 * BUILD REX ITEMS
 *
 * Native poster fields are retained.
 * Title-logo and textless-artwork fields
 * are exposed for your existing HTML.
 */

async function buildItem(
  entry,
  mediaType
) {
  var row = entry.row;

  var subject =
    row.movie ||
    row.show ||
    row;

  var title = String(
    subject.title ||
    subject.name ||
    "Untitled"
  );

  var ids = subject.ids || row.ids || {};

  var tmdbId = positiveId(
    ids.tmdb ||
    subject.tmdb_id ||
    subject.tmdbId
  );

  var imdbId = String(
    ids.imdb ||
    subject.imdb_id ||
    subject.imdbId ||
    ""
  );

  if (!tmdbId) {
    tmdbId = await resolveTmdbId(
      mediaType,
      imdbId
    );
  }

  if (!tmdbId && !/^tt\d+$/.test(imdbId)) {
    console.warn(
      "Missing usable IDs:",
      title
    );

    return null;
  }

  var item = {
    id: tmdbId
      ? mediaType + "." + tmdbId
      : imdbId,

    type: tmdbId ? "tmdb" : "imdb",
    mediaType: mediaType,
    title: title,
    rank: entry.rank,
    position: entry.rank
  };

  if (tmdbId) {
    item.tmdbId = tmdbId;

    var art = await getArtwork(
      mediaType,
      tmdbId,
      title
    );

    var poster =
      art.cleanPoster ||
      art.standardPoster;

    if (poster) {
      item.posterPath = poster;
      item.detailPoster = poster;
      item.coverUrl = tmdbUrl(poster);
    }

    if (art.cleanPoster) {
      item.cleanPosterPath =
        art.cleanPoster;
    }

    if (art.logo) {
      item.titleLogoPath = art.logo;
    }

    if (art.backdrop) {
      item.backdropPath = art.backdrop;
    }

    if (art.genres.length) {
      item.genreTitle =
        art.genres.join(" · ");
    }

    if (art.network) {
      item.originalNetwork =
        art.network;
    }

    if (art.networkLogo) {
      item.networkLogoPath =
        art.networkLogo;
    }
  }

  if (
    isNinetiesClub(
      title,
      tmdbId,
      imdbId,
      mediaType
    )
  ) {
    if (!item.posterPath) {
      item.coverUrl =
        NINETIES_CLUB_POSTER;

      item.detailPoster =
        NINETIES_CLUB_POSTER;
    }

    if (!item.genreTitle) {
      item.genreTitle = "Documentary";
    }
  }

  return item;
}

/*
 * FAST LOADING
 *
 * Preserve the working v1.2 algorithm:
 * - Four concurrent metadata jobs
 * - Complete list before returning
 * - Rex module cache for 30 minutes
 */

async function loadNativeList(
  mediaType,
  slug,
  params
) {
  var entries = await fetchTraktList(
    slug,
    mediaType,
    (params || {}).traktClientId
  );

  var result = [];

  for (
    var start = 0;
    start < entries.length;
    start += BATCH_SIZE
  ) {
    var batch = entries.slice(
      start,
      start + BATCH_SIZE
    );

    var completed = await Promise.all(
      batch.map(async function(entry) {
        try {
          return await buildItem(
            entry,
            mediaType
          );
        } catch (error) {
          console.warn(
            "Metadata failed:",
            entry.rank,
            errString(error)
          );

          return null;
        }
      })
    );

    result = result.concat(
      completed.filter(Boolean)
    );
  }

  result.sort(function(a, b) {
    return a.rank - b.rank;
  });

  if (!result.length) {
    throw new Error(
      "No usable titles for " + slug
    );
  }

  console.log(
    "TOP 20",
    mediaType,
    "items",
    result.length,
    "posters",
    result.filter(function(x) {
      return !!(
        x.posterPath ||
        x.coverUrl
      );
    }).length,
    "textless",
    result.filter(function(x) {
      return !!x.cleanPosterPath;
    }).length,
    "logos",
    result.filter(function(x) {
      return !!x.titleLogoPath;
    }).length
  );

  return result;
}

